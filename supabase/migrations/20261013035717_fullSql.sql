BEGIN;

-- 1. CATEGORIES
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    slug TEXT NOT NULL UNIQUE,
    description TEXT,
    icon TEXT,
    is_published BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. TOPICS: reusable catalog, separate from a student's personal goal.
CREATE TABLE IF NOT EXISTS public.topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    description TEXT,
    subject TEXT NOT NULL,
    difficulty_level TEXT NOT NULL DEFAULT 'beginner'
        CHECK (difficulty_level IN ('beginner', 'intermediate', 'advanced')),
    order_sequence INTEGER NOT NULL DEFAULT 1,
    source_type TEXT NOT NULL DEFAULT 'admin'
        CHECK (source_type IN ('admin', 'ai')),
    created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (name, subject)
);
CREATE INDEX IF NOT EXISTS topics_category_idx ON public.topics(category_id);
CREATE INDEX IF NOT EXISTS topics_subject_idx ON public.topics(subject);
CREATE INDEX IF NOT EXISTS topics_published_idx
    ON public.topics(is_published, category_id);

-- 3. LEARNING GOALS
CREATE TABLE IF NOT EXISTS public.learning_goals (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    topic_id BIGINT REFERENCES public.topics(id) ON DELETE SET NULL,
    requested_topic TEXT NOT NULL,
    description TEXT,
    target_level TEXT NOT NULL DEFAULT 'beginner'
        CHECK (target_level IN ('beginner', 'intermediate', 'advanced')),
    target_outcome TEXT,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'generating', 'ready', 'failed')),
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS learning_goals_user_idx
    ON public.learning_goals(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS learning_goals_status_idx
    ON public.learning_goals(status);

-- 4. LEARNING PATHS
CREATE TABLE IF NOT EXISTS public.learning_paths (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    goal_id UUID NOT NULL REFERENCES public.learning_goals(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    description TEXT,
    difficulty_level TEXT NOT NULL DEFAULT 'beginner'
        CHECK (difficulty_level IN ('beginner', 'intermediate', 'advanced')),
    estimated_hours NUMERIC(7,2),
    generation_version INTEGER NOT NULL DEFAULT 1,
    status TEXT NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'active', 'completed', 'archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS learning_paths_user_idx
    ON public.learning_paths(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS learning_paths_goal_idx
    ON public.learning_paths(goal_id);

-- 5. MATERIALS
CREATE TABLE IF NOT EXISTS public.materials (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    topic_id BIGINT REFERENCES public.topics(id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    description TEXT,
    content TEXT,
    material_type TEXT NOT NULL DEFAULT 'article'
        CHECK (material_type IN (
            'article', 'video', 'documentation', 'exercise', 'project', 'external_link'
        )),
    source_url TEXT,
    difficulty_level TEXT NOT NULL DEFAULT 'beginner'
        CHECK (difficulty_level IN ('beginner', 'intermediate', 'advanced')),
    estimated_minutes INTEGER NOT NULL DEFAULT 10 CHECK (estimated_minutes > 0),
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS materials_topic_idx
    ON public.materials(topic_id, is_published);

-- 6. LEARNING PATH STEPS
CREATE TABLE IF NOT EXISTS public.learning_path_steps (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    learning_path_id UUID NOT NULL
        REFERENCES public.learning_paths(id) ON DELETE CASCADE,
    material_id UUID REFERENCES public.materials(id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    description TEXT,
    learning_objectives JSONB NOT NULL DEFAULT '[]'::JSONB,
    prerequisite_step_ids UUID[] NOT NULL DEFAULT '{}',
    order_sequence INTEGER NOT NULL DEFAULT 1 CHECK (order_sequence > 0),
    estimated_minutes INTEGER NOT NULL DEFAULT 30 CHECK (estimated_minutes > 0),
    status TEXT NOT NULL DEFAULT 'locked'
        CHECK (status IN ('locked', 'available', 'in_progress', 'completed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (learning_path_id, order_sequence)
);
CREATE INDEX IF NOT EXISTS learning_path_steps_path_idx
    ON public.learning_path_steps(learning_path_id, order_sequence);

-- 7. QUIZ QUESTIONS
-- For production, do not expose correct_answer to student clients.
CREATE TABLE IF NOT EXISTS public.quiz_questions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    material_id UUID REFERENCES public.materials(id) ON DELETE CASCADE,
    step_id UUID REFERENCES public.learning_path_steps(id) ON DELETE CASCADE,
    question TEXT NOT NULL,
    question_type TEXT NOT NULL DEFAULT 'multiple_choice'
        CHECK (question_type IN ('multiple_choice', 'true_false', 'short_answer', 'code')),
    options JSONB NOT NULL DEFAULT '[]'::JSONB,
    correct_answer JSONB,
    explanation TEXT,
    skill_key TEXT NOT NULL,
    difficulty_level TEXT NOT NULL DEFAULT 'beginner'
        CHECK (difficulty_level IN ('beginner', 'intermediate', 'advanced')),
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (material_id IS NOT NULL OR step_id IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS quiz_questions_step_idx
    ON public.quiz_questions(step_id, is_published);
CREATE INDEX IF NOT EXISTS quiz_questions_skill_idx
    ON public.quiz_questions(skill_key);

-- 8. QUIZ ATTEMPTS
CREATE TABLE IF NOT EXISTS public.quiz_attempts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    question_id UUID NOT NULL REFERENCES public.quiz_questions(id) ON DELETE CASCADE,
    learning_path_id UUID REFERENCES public.learning_paths(id) ON DELETE SET NULL,
    answer JSONB,
    is_correct BOOLEAN NOT NULL DEFAULT FALSE,
    response_time_ms INTEGER CHECK (response_time_ms IS NULL OR response_time_ms >= 0),
    attempted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS quiz_attempts_user_idx
    ON public.quiz_attempts(user_id, attempted_at DESC);
CREATE INDEX IF NOT EXISTS quiz_attempts_question_idx
    ON public.quiz_attempts(question_id, user_id);

-- 9. STUDENT MASTERY: BKT-compatible estimates per skill.
CREATE TABLE IF NOT EXISTS public.student_mastery (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    skill_key TEXT NOT NULL,
    p_known DOUBLE PRECISION NOT NULL DEFAULT 0.1
        CHECK (p_known >= 0 AND p_known <= 1),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    correct_attempts INTEGER NOT NULL DEFAULT 0
        CHECK (correct_attempts >= 0 AND correct_attempts <= attempts),
    last_assessed_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, skill_key)
);
CREATE INDEX IF NOT EXISTS student_mastery_user_idx
    ON public.student_mastery(user_id);

-- 10. STEP PROGRESS
CREATE TABLE IF NOT EXISTS public.step_progress (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    step_id UUID NOT NULL REFERENCES public.learning_path_steps(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'not_started'
        CHECK (status IN ('not_started', 'in_progress', 'completed')),
    progress_percent INTEGER NOT NULL DEFAULT 0
        CHECK (progress_percent BETWEEN 0 AND 100),
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, step_id)
);
CREATE INDEX IF NOT EXISTS step_progress_user_idx
    ON public.step_progress(user_id, status);

-- 11. AI USAGE EVENTS
CREATE TABLE IF NOT EXISTS public.ai_usage_events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    function_name TEXT NOT NULL,
    model_name TEXT,
    input_tokens INTEGER NOT NULL DEFAULT 0 CHECK (input_tokens >= 0),
    output_tokens INTEGER NOT NULL DEFAULT 0 CHECK (output_tokens >= 0),
    status TEXT NOT NULL DEFAULT 'success'
        CHECK (status IN ('success', 'failed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ai_usage_events_user_idx
    ON public.ai_usage_events(user_id, created_at DESC);

-- 12. updated_at trigger function with a SkillPath-specific name.
CREATE OR REPLACE FUNCTION public.skillpath_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

-- Install updated_at triggers only if the exact trigger name is absent.
DO $$
DECLARE
    tbl TEXT;
BEGIN
    FOREACH tbl IN ARRAY ARRAY[
        'categories', 'topics', 'learning_goals', 'learning_paths',
        'materials', 'learning_path_steps', 'quiz_questions',
        'student_mastery', 'step_progress'
    ]
    LOOP
        IF NOT EXISTS (
            SELECT 1
            FROM pg_trigger t
            JOIN pg_class c ON c.oid = t.tgrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = 'public'
              AND c.relname = tbl
              AND t.tgname = 'skillpath_set_updated_at_trigger'
              AND NOT t.tgisinternal
        ) THEN
            EXECUTE format(
                'CREATE TRIGGER skillpath_set_updated_at_trigger
                 BEFORE UPDATE ON public.%I
                 FOR EACH ROW EXECUTE FUNCTION public.skillpath_set_updated_at()',
                tbl
            );
        END IF;
    END LOOP;
END;
$$;

